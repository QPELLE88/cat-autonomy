"""
CAT Autonomous Trucks — Fleet Telemetry Schema
Defines the data structures for truck telemetry events
streamed from autonomous vehicles to the fleet management platform.
"""
from dataclasses import dataclass, field
from typing import List, Optional
from datetime import datetime
from enum import Enum


class TruckStatus(Enum):
    AUTONOMOUS = "autonomous"
    MANUAL = "manual"
    EMERGENCY_STOP = "emergency_stop"
    MAINTENANCE = "maintenance"
    IDLE = "idle"


class EventSeverity(Enum):
    INFO = "info"
    WARNING = "warning"
    CRITICAL = "critical"


@dataclass
class GPSCoordinate:
    latitude: float
    longitude: float
    altitude_m: float
    accuracy_m: float = 2.0


@dataclass
class TruckTelemetry:
    """Core telemetry packet sent every 1 second from each truck."""
    truck_id: str
    timestamp: datetime
    gps: GPSCoordinate
    speed_kmh: float
    heading_deg: float
    load_tonnes: float
    status: TruckStatus
    fuel_level_pct: float
    engine_hours: float
    odometer_km: float


@dataclass
class ObstacleEvent:
    """Event generated when an obstacle is detected by the perception system."""
    event_id: str
    truck_id: str
    timestamp: datetime
    obstacle_type: str  # "rock", "vehicle", "personnel", etc.
    confidence: float
    gps: GPSCoordinate
    response_action: str  # "stop", "slow", "reroute", "alert_operator"
    safety_buffer_m: float
    distance_to_obstacle_m: float
    severity: EventSeverity
    resolved: bool = False
    resolution_time_s: Optional[float] = None


@dataclass
class FleetAlert:
    """Alert generated by the fleet management system based on event patterns."""
    alert_id: str
    alert_type: str
    timestamp: datetime
    affected_trucks: List[str]
    gps_center: GPSCoordinate
    radius_m: float
    description: str
    severity: EventSeverity
    acknowledged: bool = False


@dataclass
class DashboardWidget:
    """Configuration for a fleet dashboard widget."""
    widget_id: str
    widget_type: str  # "map", "chart", "table", "alert_feed", "metric"
    title: str
    data_source: str
    refresh_interval_s: int = 5
    filters: dict = field(default_factory=dict)
